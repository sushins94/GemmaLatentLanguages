def _load():
    """Returns (words, is_placeholder). Callers warn loudly on the placeholder
    so a figure can never be mistaken for a result."""
    import json
    import os

    here = os.path.dirname(os.path.abspath(__file__))
    env = os.environ.get("LLAT_WORDS", "").strip()
    if env.lower() == "placeholder":
        return _PLACEHOLDER_WORDS, True
    path = env or os.path.join(here, "words.json")
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            raw = json.load(f)
        words = []
        for w in raw:
            e = dict(w)
            # JSON has no tuples; restore the (native, roman) pairs
            for lg in ("hi", "ta", "ml"):
                if lg in e and isinstance(e[lg], list):
                    e[lg] = tuple(e[lg])
            words.append(e)
        return words, False
    return _PLACEHOLDER_WORDS, True


WORDS, IS_PLACEHOLDER = _load()