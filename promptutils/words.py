# Unrelated common English nouns, matched on NOTHING. P(correct English word)
# versus P(one of these) is a coarse specificity check: if an arbitrary English
# word peaks just as high mid-stack, the hump means "Latin-script tokens are
# likely here" rather than "this concept was retrieved". build_controls.py
# produces a properly matched version (unigram frequency and |Start(w)|) in
# promptutils/controls.json, which takes priority when present.
